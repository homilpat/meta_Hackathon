"""Tool-payload size before/after the case summary tool, on 30 held-out synthetic cases. No model calls.

"Before" = the raw-tool reads an investigator needs to see the same facts (context, AOI, human, repair, SPI
events, integrity, predictions). "After" = one get_case_summary call. Tokens are estimated as chars/4 (no
tokenizer for muse-spark is available offline), so compare the ratio, not the absolute number.
Also checks that the summary carries every source evidence id the NCR template cites (no facts lost).
Writes docs/evaluations/TOKEN_BUDGET.md and docs/evaluations/token_budget.json. Run: python -m scripts.token_budget
"""

import json
import tempfile
import uuid
from pathlib import Path
from statistics import mean

from fastapi.testclient import TestClient
from sqlalchemy.orm import Session

from app import EVAL_DIR
from app.db import Base
from app.investigator import SYSTEM_PROMPT
from app.main import create_app
from app.synthetic import generate
from app.tools import SPECS, EvidenceTools

SEEDS = range(101, 131)
BEFORE = [("get_case_context", {}), *[("get_manufacturing_events", {"entity_type": t, "limit": 50}) for t in (
    "aoi_inspections", "human_verifications", "repair_dispositions", "spi_measurements")],
          ("check_data_integrity", {}), ("get_prediction", {})]
AFTER = [("get_case_summary", {})]


def size(tools: EvidenceTools, calls) -> int:
    return sum(len(json.dumps(tools.call(n, a), ensure_ascii=False, separators=(",", ":"))) for n, a in calls)


def ids(obj) -> set[str]:
    if isinstance(obj, dict):
        return set().union(*(ids(v) for v in obj.values())) if obj else set()
    if isinstance(obj, list):
        return set().union(*(ids(v) for v in obj)) if obj else set()
    return {obj} if isinstance(obj, str) and obj.startswith(("EV-", "PRED-")) else set()


def main() -> None:
    app = create_app(f"sqlite:///{(Path(tempfile.mkdtemp()) / 'tok.db').as_posix()}")
    Base.metadata.create_all(app.state.engine)
    c = TestClient(app)

    def call(method, path, body=None):
        r = c.request(method, path, json=body, headers={"X-User": "alice", "Idempotency-Key": uuid.uuid4().hex})
        assert r.status_code < 300, (path, r.text)
        return r.json()

    call("POST", "/models/train", {"seed": 11})
    rows, missing = [], []
    for seed in SEEDS:
        cid = f"TOK-{seed}"
        call("POST", "/cases", {"case_id": cid})
        call("POST", f"/cases/{cid}/sources", generate(seed))
        if seed % 2 == 0:
            call("POST", f"/cases/{cid}/predictions", {})
        ncr_ids = {e for cl in call("POST", f"/cases/{cid}/ncr", {})["claims"] for e in cl["evidence_ids"]}
        with Session(app.state.engine) as s:
            t = EvidenceTools(s, cid)
            before, after = size(t, BEFORE), size(t, AFTER)
            lost = ncr_ids - ids(t.call("get_case_summary", {}))
        rows.append({"case": cid, "scored": seed % 2 == 0, "before_chars": before, "after_chars": after})
        if lost:
            missing.append({"case": cid, "ncr_evidence_not_in_summary": sorted(lost)})
    c.close()
    app.state.engine.dispose()
    b, a = mean(r["before_chars"] for r in rows), mean(r["after_chars"] for r in rows)
    fixed = len(json.dumps(SPECS)) + len(SYSTEM_PROMPT)
    out = {"cases": len(rows), "tool_calls": {"before": len(BEFORE), "after": len(AFTER)},
           "mean_tool_payload_chars": {"before": round(b), "after": round(a)},
           "mean_tool_payload_tokens_est": {"before": round(b / 4), "after": round(a / 4)},
           "reduction": round(1 - a / b, 3), "fixed_prompt_and_tool_specs_chars": fixed,
           "ncr_facts_missing_from_summary": missing, "per_case": rows}
    (EVAL_DIR / "token_budget.json").write_text(json.dumps(out, indent=2), encoding="utf-8")
    (EVAL_DIR / "TOKEN_BUDGET.md").write_text(f"""# Investigation token budget (tool payloads)

Generated by `python -m scripts.token_budget` on {len(rows)} held-out SYNTHETIC cases (seeds {SEEDS.start}–{SEEDS.stop - 1},
half scored by the SPI model). No model was called.

| | tool calls | mean tool-result chars | est. tokens (chars/4) |
|---|---|---|---|
| Before: raw reads (context, 4 event types, integrity, predictions) | {len(BEFORE)} | {round(b)} | {round(b / 4)} |
| After: `get_case_summary` | {len(AFTER)} | {round(a)} | {round(a / 4)} |

Tool-result payload reduction: **{out['reduction']:.1%}**. Fixed per-request overhead (system prompt + tool specs):
{fixed} chars, sent on every round, so fewer rounds also save it again each time.
Every source/model evidence id cited by the NCR template is present in the summary: {len(missing) == 0}
({len(missing)} cases missing ids).

Not measured yet: whether the LIVE model actually calls fewer tools or writes better reports with the summary
(needs a key; planned as an extra row in the A/B/C/D comparison). The token estimate is approximate.
""", encoding="utf-8")
    print(json.dumps({k: v for k, v in out.items() if k != "per_case"}))


if __name__ == "__main__":
    main()
